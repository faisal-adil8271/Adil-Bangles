// Common Hinglish / English phonetic transliteration mapping for unknown words
const CONSONANT_MAP = {
    kh: "ख", gh: "घ", ch: "च", chh: "छ", jh: "झ", th: "थ", dh: "ध", bh: "भ", ph: "फ", sh: "श",
    k: "क", g: "ग", c: "क", j: "ज", t: "ट", d: "ड", n: "न", p: "प", b: "ब", m: "म", y: "य",
    r: "र", l: "ल", v: "व", w: "व", s: "स", h: "ह", z: "ज़", f: "फ़", q: "क", x: "क्स"
};

const VOWEL_MATRA = {
    aa: "ा", ee: "ी", oo: "ू", ai: "ै", au: "ौ", a: "", i: "ि", u: "ु", e: "े", o: "ो"
};

const INITIAL_VOWEL = {
    aa: "आ", a: "अ", ee: "ई", i: "इ", oo: "ऊ", u: "उ", e: "ए", ai: "ऐ", o: "ओ", au: "औ"
};

export function phoneticTransliterate(word) {
    if (!word || typeof word !== "string") return "";
    let str = word.toLowerCase().trim();
    if (!str) return "";

    let result = "";
    let i = 0;

    // Check if word starts with a vowel
    for (const v of ["aa", "ee", "oo", "ai", "au", "a", "i", "u", "e", "o"]) {
        if (str.startsWith(v)) {
            result += INITIAL_VOWEL[v];
            i += v.length;
            break;
        }
    }

    while (i < str.length) {
        // Try two-letter consonant first
        const twoC = str.substring(i, i + 2);
        const oneC = str.substring(i, i + 1);

        let consChar = "";
        let step = 0;

        if (CONSONANT_MAP[twoC]) {
            consChar = CONSONANT_MAP[twoC];
            step = 2;
        } else if (CONSONANT_MAP[oneC]) {
            consChar = CONSONANT_MAP[oneC];
            step = 1;
        }

        if (consChar) {
            result += consChar;
            i += step;

            // Check following vowel matra
            const nextTwoV = str.substring(i, i + 2);
            const nextOneV = str.substring(i, i + 1);

            if (VOWEL_MATRA[nextTwoV] !== undefined) {
                result += VOWEL_MATRA[nextTwoV];
                i += 2;
            } else if (VOWEL_MATRA[nextOneV] !== undefined) {
                result += VOWEL_MATRA[nextOneV];
                i += 1;
            }
        } else {
            // Check standalone vowel or punctuation
            const vTwo = str.substring(i, i + 2);
            const vOne = str.substring(i, i + 1);

            if (INITIAL_VOWEL[vTwo]) {
                result += INITIAL_VOWEL[vTwo];
                i += 2;
            } else if (INITIAL_VOWEL[vOne]) {
                result += INITIAL_VOWEL[vOne];
                i += 1;
            } else {
                result += str[i];
                i += 1;
            }
        }
    }

    return result || word;
}

export function translateWithDictionary(text) {
    if (!text) return "";
    const clean = text.trim();
    const lower = clean.toLowerCase();

    // 1. Direct whole-phrase match
    if (DICTIONARY[lower]) {
        return DICTIONARY[lower];
    }

    // 2. Multi-word phrase substitution (sorted by length descending)
    let working = clean;
    const sortedKeys = Object.keys(DICTIONARY).sort((a, b) => b.length - a.length);

    for (const key of sortedKeys) {
        const regex = new RegExp(`\\b${key}\\b`, "gi");
        if (regex.test(working)) {
            working = working.replace(regex, DICTIONARY[key]);
        }
    }

    // 3. For any remaining pure English Latin words, apply phonetic transliteration
    const words = working.split(/\s+/);
    const translatedWords = words.map((w) => {
        // If word is already in Devanagari or numbers/symbols, keep it
        if (/[\u0900-\u097F]/.test(w) || /^[^a-zA-Z]+$/.test(w)) {
            return w;
        }
        const stripped = w.replace(/[^a-zA-Z]/g, "").toLowerCase();
        if (DICTIONARY[stripped]) {
            return DICTIONARY[stripped];
        }
        // Phonetic fallback
        return phoneticTransliterate(w);
    });

    return translatedWords.join(" ").replace(/\s+/g, " ").trim();
}

export async function translateTextToHindi(text) {
    if (!text || !text.trim()) return "";
    const clean = text.trim();
    const lower = clean.toLowerCase();

    // Fast return if exact match exists in dictionary
    if (DICTIONARY[lower]) {
        return DICTIONARY[lower];
    }

    // 1. Try Google Translate public client endpoint if reachable
    try {
        const url = `https://translate.googleapis.com/translate_a/single?client=gtx&sl=auto&tl=hi&dt=t&q=${encodeURIComponent(clean)}`;
        const res = await fetch(url, { signal: AbortSignal.timeout(2000) });
        if (res.ok) {
            const data = await res.json();
            const translated = (data[0] || []).map((chunk) => chunk[0]).join("").trim();
            if (translated && translated !== clean) {
                return translated;
            }
        }
    } catch {
        // Fallback to backend or dictionary
    }

    // 2. Try backend endpoint
    try {
        const res = await fetch("/api/translate", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ text: clean, target: "hi" }),
        });
        if (res.ok) {
            const data = await res.json();
            if (data?.translatedText && data.translatedText !== clean) {
                return data.translatedText;
            }
        }
    } catch {
        // Fallback to dictionary
    }

    // 3. Robust dictionary + phonetic fallback
    return translateWithDictionary(clean);
}
